//! Optional WGSL element shaders, translated by `rusterize-shader-build`.
//!
//! System OpenGL or browser WebGL 2 executes in an owned offscreen context.
//! The RGBA result is an ordinary [`Image`], composited by the platform Canvas.
//! This compatibility path performs GPU readback; cache static results and keep
//! animated regions small. No WGSL compiler or general-purpose engine is shipped.
#[cfg(not(all(target_arch = "wasm32", target_os = "unknown")))]
mod native;
#[cfg(not(all(target_arch = "wasm32", target_os = "unknown")))]
pub use native::ShaderRenderer;
#[cfg(all(target_arch = "wasm32", target_os = "unknown"))]
mod browser;
#[cfg(all(target_arch = "wasm32", target_os = "unknown"))]
pub use browser::ShaderRenderer;

use crate::{Canvas, Error, Image, Rect};

/// Generated by `rusterize_shader_build::compile_file` for the target platform.
#[derive(Debug)]
pub struct ShaderSource {
    #[doc(hidden)]
    pub vertex: &'static str,
    #[doc(hidden)]
    pub fragment: &'static str,
    #[doc(hidden)]
    pub uniform_block: Option<&'static str>,
    #[doc(hidden)]
    pub texture_uniform: Option<&'static str>,
}

/// Values visible as `params.time` and `params.data[0..4]` in WGSL.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct ShaderParams {
    pub time: f32,
    pub data: [[f32; 4]; 4],
}

pub struct Shader<'a> {
    pub source: &'static ShaderSource,
    pub params: ShaderParams,
    pub image: Option<&'a Image>,
}
impl ShaderSource {
    pub fn shader(&'static self, params: ShaderParams) -> Shader<'static> {
        Shader {
            source: self,
            params,
            image: None,
        }
    }
}
impl<'a> Shader<'a> {
    pub fn with_image<'b>(self, image: &'b Image) -> Shader<'b> {
        Shader {
            source: self.source,
            params: self.params,
            image: Some(image),
        }
    }
}

#[derive(PartialEq)]
struct CacheKey {
    source: usize,
    size: [u32; 2],
    values: [u32; 20],
    image: u64,
}

fn validate_request(
    shader: &Shader<'_>,
    size: [u32; 2],
    scale: f32,
    max: u32,
) -> Result<(), Error> {
    if size.contains(&0)
        || size.iter().any(|n| *n > max)
        || size[0] as u64 * size[1] as u64 > 4 * 1024 * 1024
    {
        return Err(Error(
            "Shader output must fit the device, 4096 per side and 4 million pixels".into(),
        ));
    }
    if !scale.is_finite()
        || scale <= 0.0
        || !shader.params.time.is_finite()
        || shader.params.data.iter().flatten().any(|n| !n.is_finite())
    {
        return Err(Error(
            "Shader scale and parameters must be finite; scale must be positive".into(),
        ));
    }
    if shader
        .image
        .is_some_and(|i| i.width() > max || i.height() > max)
    {
        return Err(Error("Shader input exceeds the device texture size".into()));
    }
    Ok(())
}

impl Canvas<'_> {
    /// Render a WGSL element and insert it at this position in the display list.
    /// Existing clip/transform/ordering rules apply. Pass Viewport::scale for DPI.
    pub fn shader(
        &mut self,
        renderer: &mut ShaderRenderer,
        bounds: Rect,
        scale: f32,
        shader: &Shader<'_>,
    ) {
        if !bounds.valid() || !scale.is_finite() || scale <= 0.0 {
            self.fail("invalid shader bounds or scale");
            return;
        }
        if bounds.width == 0.0 || bounds.height == 0.0 {
            return;
        }
        let size = [
            (bounds.width * scale).ceil() as u32,
            (bounds.height * scale).ceil() as u32,
        ];
        match renderer.render(shader, size, scale) {
            Ok(image) => self.image(&image, bounds, 1.0),
            Err(error) => self.fail(&error.0),
        }
    }
}
